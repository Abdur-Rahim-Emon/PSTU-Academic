        // TODO add your handling code here:
       if(list.getSelectedItem().equals("Select an Option") || temp1.getText().equals(""))
       {
           JOptionPane.showMessageDialog(null,"input value", " Error", 2);
       }
       else if(list.getSelectedItem().equals("Celcious to Fahrenhit")){
          double temp=Double.parseDouble(temp1.getText());
         double rslt=(9*temp/5)+32;
         String s=String.format("%3f",rslt);
        result.setText(""+rslt);
       }
       else if(list.getSelectedItem().equals("Fahrenhit to Celcious")){
            double temp=Double.parseDouble(temp1.getText());
         double rslt=(temp-32)*(5/9);
         result.setText(""+rslt);
       }
       else if(list.getSelectedItem().equals("Celcious to kalvin")){
            double temp=Double.parseDouble(temp1.getText());
         double rslt=temp+273;
         result.setText(""+rslt);
       }
       else if(list.getSelectedItem().equals("kalvin to Celcious")){
            double temp=Double.parseDouble(temp1.getText());
         double rslt=(9*temp/5)+32;
         result.setText(""+rslt);
       }
     

