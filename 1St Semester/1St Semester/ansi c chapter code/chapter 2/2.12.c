#include<stdio.h>
#include<math.h>
int main()
{
    int x,y;
    scanf("%d %d",&x,&y);
    int sum,dif,pro,div;
    sum=x+y;
    dif=x-y;
    pro=x*y;
    div=x/y;
    printf("summation: %d\n",sum);
    printf("Difference: %d\n",dif);
    printf("product : %d\n",pro);
    printf("Division: %d\n",div);

}
